@dataclass(frozen=True)
class Tuning:
    """The knobs the acceptance report iterates. Starting values from RPD-8-2/6."""

    w_gmsc: float = 0.45
    w_ts: float = 0.25
    w_mpg: float = 0.30
    # RPD-8-6 starts at 8 ("close to the synthetic per-field spread"). Chosen as the
    # LARGEST value on a 0.25 grid that passes the report's drag check in every season
    # 2009-2025 and pooled (>= 95% of the qualified pool within 8 of the synthetic mean,
    # SD(T'-T) <= 4) and the full-rating clamp check (<= 20%), on the version-2 builder
    # AFTER every RPD-8 critic fix; structural checks only, never the validation set:
    #   spread  drag (worst season share / max SD / pooled)  clamp
    #   4.00    (was the pre-fix choice)
    #   4.50    96.5% / 3.51 / 97.7%   13.3%
    #   4.75    96.0% / 3.57 / 97.2%   13.8%   <- chosen
    #   4.90    94.9% (2019 fails) / 3.61 / 96.9%   14.0%
    #   5.00    94.9% (2023 fails) / 3.64 / 96.7%   14.2%
    #   6.00    12 of 17 seasons and pooled fail (94.1%)   16.0%
    # The critic-preferred 6-8 fails the drag check: even with the duplicate fields gone
    # (B3) the gap between the synthetic and real means has a spread-independent floor.
    # The report's evidence-share line measures 21.6% of a real field's variance over the
    # qualified pool at 4.75 (Var(4.75 u) = 22.6 against a talent variance that is larger
    # than the ladder's 54.6 once the linear tail is in), 94.7% inside talent 74-78.
    u_spread: float = 4.75
    # RPC-4-4: the swap ranks on `w * z(evidence) + (1 - w) * z(level value)` within the
    # cell; 0.0 reproduces the level formula exactly. The design's default was 1.0 (pure
    # evidence), but that fails the drag check above in 2024 (454 of 481 within 8, need
    # 457): a low-talent guard who blocks shots inherits a star guard's value, which
    # moves his real-field mean away from his synthetic one. Chosen the way u_spread was:
    # the LARGEST value on a 0.05 grid that passes the drag check in every season 2009-2025,
    # structural checks only, before any named-player or simulation read (RPC-12's
    # two-set rule):
    #   w      drag worst season           T1 pooled / worst season
    #   1.00   94.4% (2024 fails)          0.840 / 0.764
    #   0.90   94.4% (2024 fails)          0.840 / 0.766
    #   0.80   94.8% (2024 fails)          0.836 / 0.762
    #   0.75   94.8% (2024 fails)          0.832 / 0.760
    #   0.70   95.0% (2024, 457 of 481)    0.827 / 0.757   <- chosen
    #   0.65   95.1% (2023)                0.820 / 0.753
    #   0.60   95.3% (2023)                0.811 / 0.744
    #   (0.00, the level formula alone: 96.0% (2023), T1 0.644 / 0.598)
    swap_evidence_weight: float = 0.70


DEFAULT_TUNING = Tuning()


def _clamp(value: float, lo: float, hi: float) -> float:
    return min(max(value, lo), hi)


# --------------------------------------------------------------------------- ladder


def tier_ladder() -> tuple[float, ...]:
    """The 420 talent values the tier structure defines, best first. Each tier
    contributes its normal quantile points `(i - 0.5) / n`; pooling and sorting makes
    rank -> talent monotone while keeping the mixture (weighted mean 69.71, SD 7.39)."""
    slots: dict = defaultdict(int)
    for tier in TIER_BY_SLOT:
        slots[tier] += 1
    # TIER_BY_SLOT is one 14-man roster: 1 star, 4 starters, 3 rotation, 6 bench. The
    # 30/120/90/180 = 420 league slots are 30 rosters of it.
    values: list[float] = []
    normal = NormalDist()
    for tier, per_roster in slots.items():
        spec = _TIER_TALENT[tier]
        count = per_roster * 30
        values.extend(
            spec.mean + spec.sd * normal.inv_cdf((i - 0.5) / count) for i in range(1, count + 1)
        )
    assert len(values) == LADDER_SLOTS
    return tuple(sorted(values, reverse=True))


_LADDER = tier_ladder()


def talent_for_rank(rank: int, qualified: int) -> float:
    """Talent `T` for a 1-based rank in a qualified pool of `qualified` players.
    Ranks 1..420 read the ladder; ranks beyond fall linearly to `TAIL_FLOOR` at the last
    qualified rank. A rank past the pool (an unqualified player ranking below every
    qualified one) gets the floor. Clamped to the sim's talent range."""
    if rank <= LADDER_SLOTS:
        value = _LADDER[rank - 1]
    else:
        tail_top = min(TAIL_TOP, _LADDER[-1])
        last = max(qualified, LADDER_SLOTS + 1)
        if rank > last:
            value = TAIL_FLOOR
        else:
            frac = (rank - (LADDER_SLOTS + 1)) / max(last - (LADDER_SLOTS + 1), 1)
            value = tail_top + (TAIL_FLOOR - tail_top) * frac
    return _clamp(value, *_TALENT_CLAMP)


# --------------------------------------------------------------------------- blend


def blend_takes(minutes: float, prior_minutes: Sequence[float]) -> tuple[float, list[float]]:
    """RPD-8-4: `(used0, takes)` where `used0 = min(minutes, 1500)` and `takes[i]` is
    how many minutes of the `i+1`-seasons-back season fill the gap, most recent first.
    `prior_minutes[i]` is that season's raw minutes for this player (0 if absent)."""
    used0 = min(minutes, FULL_CONFIDENCE_MINUTES)
    fill = FULL_CONFIDENCE_MINUTES - used0
    takes: list[float] = []
    for back, prior in enumerate(prior_minutes[:BLEND_LOOKBACK], start=1):
        take = min(fill, max(prior, 0.0) * AVAILABILITY_DECAY**back)
        takes.append(take)
        fill -= take
    return used0, takes


def blend_z(
    z_now: float, used0: float, takes: Sequence[float], z_priors: Sequence[float | None]
) -> float:
    """`z_eff = (used0 * z_now + sum(take_i * z_prior_i)) / 1500`; a prior season that
    lacks this metric contributes nothing (the unfilled part stays at 0, league mean)."""
    total = used0 * z_now
    for take, z_prior in zip(takes, z_priors, strict=False):
        if z_prior is not None:
            total += take * z_prior
    return total / FULL_CONFIDENCE_MINUTES


