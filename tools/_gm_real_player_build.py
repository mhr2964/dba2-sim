@dataclass
class BuildStats:
    season: int
    players: int = 0
    qualified: int = 0
    fit_misses: int = 0  # displayed overall != round(T) after the solver
    fit_outside_tolerance: int = 0  # |overall - round(T)| > 1
    advanced_recovered: int = 0
    advanced_raw: int = 0
    missing_priors: list[int] = field(default_factory=list)


def _prior_evidence(
    season: int, evidence: Mapping[int, SeasonEvidence], ref: str
) -> list[PlayerEvidence | None]:
    out: list[PlayerEvidence | None] = []
    for back in range(1, BLEND_LOOKBACK + 1):
        prior = evidence.get(season - back)
        out.append(prior.players.get(ref) if prior else None)
    return out


def build_season(
    season: int,
    evidence: Mapping[int, SeasonEvidence],
    legacy: LegacyIndex,
    tuning: Tuning = DEFAULT_TUNING,
) -> tuple[dict, BuildStats]:
    now = evidence[season]
    stats = BuildStats(season=season)
    stats.missing_priors = [
        season - back for back in range(1, BLEND_LOOKBACK + 1) if (season - back) not in evidence
    ]
    # which prior raw seasons fed this season's blend, so two rebuilds of one season off
    # different raw sets are distinguishable on disk (critic minor 3)
    prior_seasons = [
        season - back for back in range(1, BLEND_LOOKBACK + 1) if (season - back) in evidence
    ]
    refs = sorted(now.players)

    impact: dict[str, float] = {}
    z_eff: dict[str, dict[str, float]] = {}
    filled: dict[str, float] = {}
    effective: dict[str, float] = {}
    for ref in refs:
        cur = now.players[ref]
        priors = _prior_evidence(season, evidence, ref)
        used0, takes = blend_takes(cur.minutes, [p.minutes if p else 0.0 for p in priors])
        blended = {
            name: blend_z(z_now, used0, takes, [p.z.get(name) if p else None for p in priors])
            for name, z_now in cur.z.items()
        }
        for name in PHYSICAL_METRICS:  # a physical does not thin out with a short sample
            blended[name] = cur.z[name]
        z_eff[ref] = blended
        filled[ref] = sum(takes)
        effective[ref] = used0 + filled[ref]
        impact[ref] = (
            tuning.w_gmsc * blended["gmsc36"]
            + tuning.w_ts * blended["ts_scoring"]
            + tuning.w_mpg * cur.mpg_z
        )

    qualified = [r for r in refs if effective[r] >= QUALIFY_MINUTES]
    position = resolve_positions(
        {
            ref: _position_facts(now.players[ref].raw, effective[ref] >= QUALIFY_MINUTES)
            for ref in refs
        }
    )
    ranked = sorted(qualified, key=lambda r: (-impact[r], r))
    stats.qualified = len(ranked)
    rank_of = {ref: i for i, ref in enumerate(ranked, start=1)}
    ranked_impacts = [impact[r] for r in ranked]

    talent: dict[str, float] = {}
    shown_rank: dict[str, int] = {}
    for ref in refs:
        if ref in rank_of:
            rank = rank_of[ref]
            talent[ref] = talent_for_rank(rank, len(ranked))
        else:
            # insertion rank among the qualified: 1 + how many outrank this player
            rank = 1 + sum(1 for value in ranked_impacts if value > impact[ref])
            talent[ref] = min(talent_for_rank(rank, len(ranked)), UNQUALIFIED_TALENT_CAP)
        shown_rank[ref] = rank

    field_z: dict[str, dict[str, float]] = {}
    field_evidence: dict[str, dict[str, float]] = {}  # the blended z before residual_u
    for name, weights in FIELD_METRIC_WEIGHTS.items():
        values: dict[str, float] = {}
        for ref in refs:
            if all(metric in z_eff[ref] for metric in weights):
                values[ref] = sum(w * z_eff[ref][metric] for metric, w in weights.items())
        field_evidence[name] = values
        field_z[name] = residual_u(values, impact, position, ranked)

    level: dict[str, dict[str, int]] = {}
    for ref in refs:
        cur = now.players[ref]
        if not cur.raw.get("first_team"):
            # `seed_dev_league` reads row["team"]["abbreviation"] unguarded: refuse to write a
            # row without one rather than leave a KeyError for the loader (critic minor 6)
            raise ValueError(
                f"{cur.raw['first_name']} {cur.raw['last_name']} (external_ref {ref}), season "
                f"{season}: raw entry has no first_team, so no team can be assigned"
            )
        offsets = POSITION_RATING_OFFSETS[position[ref]]
        t = talent[ref]
        level[ref] = {}
        for name in REAL_FIELDS:
            if ref in field_z[name]:
                raw_value = t + offsets[name] + tuning.u_spread * field_z[name][ref]
                level[ref][name] = int(round(_clamp(raw_value, 25, 99)))
    swapped = swap_cells(
        level, field_evidence, position, ranked, weight=tuning.swap_evidence_weight
    )
    u_reach = position_residual(
        {ref: sum(w * z_eff[ref][m] for m, w in REACH_WEIGHTS.items()) for ref in refs},
        position,
        ranked,
    )

    players_out: list[dict] = []
    for ref in refs:
        cur = now.players[ref]
        pos = position[ref]
        t = talent[ref]
        real = swapped[ref]
        target = int(_clamp(round(t), 25, 99))
        fit = fit_synthetic_remainder(
            seed_key=f"{ref}:{season}",
            position=pos,
            real_fields=real,
            target_overall=target,
            hidden_talent=t,
        )
        if fit.overall != target:
            stats.fit_misses += 1
            if abs(fit.overall - target) > 1:
                stats.fit_outside_tolerance += 1

        advanced = cur.advanced_source is not None
        if cur.advanced_source == "raw":
            stats.advanced_raw += 1
        elif cur.advanced_source == "recovered":
            stats.advanced_recovered += 1
        weight = _clamp(effective[ref] / FULL_CONFIDENCE_MINUTES, 0.0, 1.0)
        confidence = round((0.55 if advanced else 0.4) + 0.3 * weight, 2)
        meta = {
            "games_played": cur.games,
            "minutes_total": round(cur.minutes, 1),
            "band": "advanced_tracking" if advanced else "box_score_only",
            "builder_version": REAL_BUILDER_VERSION,
            "minutes_per_game": round(cur.minutes / cur.games, 2) if cur.games else 0.0,
            "impact_rank": shown_rank[ref],
            "blend_filled_minutes": round(filled[ref], 1),
            "effective_minutes": round(effective[ref], 1),
            "qualified": ref in rank_of,
            "impact": round(impact[ref], 4),
            "talent": round(t, 3),
            "synthetic_talent": round(fit.t_prime, 3),
            "advanced_source": cur.advanced_source,
            "prior_seasons": prior_seasons,
        }
        if advanced:
            meta["advanced_z"] = {n: round(cur.z[n], 4) for n in ADVANCED_REAL_FIELDS}
        for name in SWAP_FIELDS:  # RPC-4-5: what the swap ranked on and what it replaced
            if name in level[ref]:
                meta[f"{name}_evidence_z"] = round(field_evidence[name][ref], 4)
                meta[f"{name}_level_value"] = level[ref][name]
        team_code = REAL_DATA_TEAM_CODE.get(cur.raw.get("first_team"), cur.raw.get("first_team"))
        row = {
            "external_ref": ref,
            "first_name": cur.raw["first_name"],
            "last_name": cur.raw["last_name"],
            "primary_position": pos.value,
            "height_in": cur.raw["height_in"],
            "weight_lb": cur.raw["weight_lb"],
            "wingspan_in": wingspan_estimate(cur.raw["height_in"], u_reach[ref]),
            "draft_year": cur.raw.get("draft_year"),
            "season": season,
            "ratings": {name: fit.ratings[name] for name in RATING_FIELD_ORDER},
            "source": "real_stat_derived",
            "confidence": confidence,
            "derived_from_season": season,
            "meta": meta,
        }
        row["team"] = dict(legacy.team(season, team_code))
        players_out.append(row)
    stats.players = len(players_out)

    seed = {
        "_note": (
            f"Real BDL-derived player ratings for the {season} season, builder version "
            f"{REAL_BUILDER_VERSION} (RPD-8, docs/design/real-player-ratings-v2.md): talent from "
            "an impact rank mapped onto the synthetic tier ladder, measured scoring/shooting/"
            "creation fields, synthetic remainder fitted to the displayed overall. Built by "
            "tools/_gm_real_player_build.py from seeds/real_players_raw; birth_date is still a "
            "placeholder."
        ),
        "season": season,
        "players": players_out,
    }
    return seed, stats


# --------------------------------------------------------------------------- peak ages


def _age_in_season(season: int, effective_draft_year: int) -> int:
    return season - effective_draft_year + DRAFT_AGE_ANCHOR


def apply_peak_ages(seeds: Mapping[int, dict], context: Mapping[int, dict] | None = None) -> int:
    """RPD-8-9: the near-peak-band method of `_gm_real_player_peak_age.py` (career-best
    overall, every season within 3 points of it, min/max age of that set; a missing or
    implausible BDL draft year anchors on the career's earliest season instead), over the
    seasons in `seeds` PLUS the version-2 seasons in `context`, so a partial rebuild sees
    the same careers as `--all` (a career-best season outside the requested range would
    otherwise move the window; found by the RPD-8 code critic, B1). A season in both is
    taken from `seeds` (it is the one being rebuilt). Only `seeds` rows are written;
    `context` is read-only. A career's legacy seasons are on another scale and never
    enter. Writes `ratings.peak_age_start/end` in place; returns players in `seeds`."""
    careers: dict[str, list[tuple[int, int, int | None]]] = defaultdict(list)
    for season, seed in {**(context or {}), **seeds}.items():
        for row in seed["players"]:
            overall = compute_overall(
                SimpleNamespace(**row["ratings"]), Position(row["primary_position"])
            )
            careers[row["external_ref"]].append((season, overall, row["draft_year"]))
    windows: dict[str, tuple[int, int]] = {}
    for ref, entries in careers.items():
        first_season = min(s for s, _, _ in entries)
        draft_year = entries[0][2]
        plausible = draft_year is not None and (
            0 <= first_season - draft_year <= MAX_YEARS_DRAFTED_BEFORE_FIRST_SEASON
        )
        effective = draft_year if plausible else first_season
        aged = [(_age_in_season(s, effective), o) for s, o, _ in entries]
        best = max(o for _, o in aged)
        near = [age for age, o in aged if o >= best - PEAK_NEAR_TOLERANCE]
        windows[ref] = (min(near), max(near))
    written = set()
    for seed in seeds.values():
        for row in seed["players"]:
            start, end = windows[row["external_ref"]]
            row["ratings"]["peak_age_start"] = start
            row["ratings"]["peak_age_end"] = end
            written.add(row["external_ref"])
    return len(written)


def load_version_two_context(directory: Path, exclude: Sequence[int]) -> dict[int, dict]:
    """The season files already in `directory` that are wholly builder version 2 and not
    in `exclude`: the careers `apply_peak_ages` must also see. A missing directory, a
    legacy or mixed file, or an unreadable name is simply not context."""
    out: dict[int, dict] = {}
    if not directory.is_dir():
        return out
    for path in sorted(directory.glob("[12][0-9][0-9][0-9].json")):
        season = int(path.stem)
        if season in exclude:
            continue
        seed = json.loads(path.read_text(encoding="utf-8"))
        rows = seed.get("players") or []
        if rows and all(
            (row.get("meta") or {}).get("builder_version") == REAL_BUILDER_VERSION for row in rows
        ):
            out[season] = seed
    return out


