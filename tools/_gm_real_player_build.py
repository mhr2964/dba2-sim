def available_raw_seasons(raw_dir: Path) -> list[int]:
    return sorted(int(p.stem) for p in raw_dir.glob("[12][0-9][0-9][0-9].json"))


def load_raw(raw_dir: Path, season: int) -> dict:
    return json.loads((raw_dir / f"{season}.json").read_text(encoding="utf-8"))


def build_seasons(
    seasons: Sequence[int],
    *,
    raw_dir: Path = RAW_DIR,
    legacy_dir: Path = LEGACY_DIR,
    tuning: Tuning = DEFAULT_TUNING,
    peak_context_dir: Path | None = None,
) -> tuple[dict[int, dict], dict[int, BuildStats]]:
    """Every requested season built, peak ages applied after all of them. Priors are
    read from whatever raw seasons exist up to three before each requested one. Peak ages
    also see the version-2 seasons already in `peak_context_dir` (the out-dir), so a
    partial rebuild leaves them as `--all` would."""
    on_disk = set(available_raw_seasons(raw_dir))
    missing = [s for s in seasons if s not in on_disk]
    if missing:
        raise FileNotFoundError(f"no raw file for season(s) {missing} in {raw_dir}")
    legacy = LegacyIndex(legacy_dir)
    needed = sorted({s - back for s in seasons for back in range(BLEND_LOOKBACK + 1)} & on_disk)
    evidence = {s: season_evidence(s, load_raw(raw_dir, s), legacy) for s in needed}
    seeds: dict[int, dict] = {}
    stats: dict[int, BuildStats] = {}
    for season in seasons:
        seeds[season], stats[season] = build_season(season, evidence, legacy, tuning)
    context = load_version_two_context(peak_context_dir, seasons) if peak_context_dir else None
    apply_peak_ages(seeds, context)
    return seeds, stats


def write_seeds(seeds: Mapping[int, dict], out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for season, seed in sorted(seeds.items()):
        path = out_dir / f"{season}.json"
        path.write_text(json.dumps(seed, indent=2), encoding="utf-8")
        written.append(path)
    return written


def main(argv: Sequence[str]) -> int:
    args = list(argv[1:])
    out_dir = DEFAULT_OUT_DIR
    raw_dir, legacy_dir = RAW_DIR, LEGACY_DIR
    allow_seeds_dir = "--allow-seeds-dir" in args
    args = [a for a in args if a != "--allow-seeds-dir"]
    everything = "--all" in args
    args = [a for a in args if a != "--all"]
    for flag in ("--out-dir", "--raw-dir", "--legacy-dir"):
        if flag in args:
            i = args.index(flag)
            if i + 1 >= len(args):
                print(f"{flag} needs a directory", file=sys.stderr)
                return 1
            value = Path(args[i + 1])
            del args[i : i + 2]
            if flag == "--out-dir":
                out_dir = value
            elif flag == "--raw-dir":
                raw_dir = value
            else:
                legacy_dir = value
    try:
        seasons = available_raw_seasons(raw_dir) if everything else sorted(int(a) for a in args)
    except ValueError:
        print("seasons must be integers", file=sys.stderr)
        return 1
    if not seasons:
        print(
            "Usage: python -m tools._gm_real_player_build (--all | <season> ...) [--out-dir DIR]",
            file=sys.stderr,
        )
        return 1
    if out_dir.resolve() == LEGACY_DIR.resolve():
        if not allow_seeds_dir:
            print(
                f"refusing to write into {LEGACY_DIR}: pass --allow-seeds-dir to overwrite the "
                "committed seeds deliberately",
                file=sys.stderr,
            )
            return 1
        if not everything:
            print(
                f"refusing a partial build into {LEGACY_DIR}: the committed seeds are only "
                "consistent when every raw season is rebuilt together, so use --all",
                file=sys.stderr,
            )
            return 1
    seeds, stats = build_seasons(
        seasons, raw_dir=raw_dir, legacy_dir=legacy_dir, peak_context_dir=out_dir
    )
    write_seeds(seeds, out_dir)
    for season in seasons:
        s = stats[season]
        gaps = f" priors-not-on-disk={s.missing_priors}" if s.missing_priors else ""
        print(
            f"season={season}: {s.players} players, {s.qualified} qualified, "
            f"fit_misses={s.fit_misses} (>1pt: {s.fit_outside_tolerance}), "
            f"advanced raw/recovered={s.advanced_raw}/{s.advanced_recovered}{gaps}"
        )
    print(f"-> {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
