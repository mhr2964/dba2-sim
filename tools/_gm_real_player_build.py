def _per36(total: float, minutes: float) -> float:
    return total * 36.0 / minutes if minutes > 0 else 0.0


def _shrunk_pct(made: float, attempts: float, prior_pct: float) -> float:
    return (made + SHRINK_PRIOR_ATTEMPTS * prior_pct) / (attempts + SHRINK_PRIOR_ATTEMPTS)


def raw_metrics(entries: Sequence[Mapping]) -> dict[str, dict[str, float]]:
    """Per player, one raw float per evidence metric (higher is better) plus `mpg`,
    for the season's whole pool. The 12 existing metrics are computed by the ETL's own
    function; the rest are RPD-8-5's and RPD-8-2's definitions."""
    league = defaultdict(float)
    for entry in entries:
        for name, value in entry["totals"].items():
            league[name] += value
    lg_fg3 = league["fg3m"] / league["fg3a"] if league["fg3a"] > 0 else 0.0
    fg2a_total = league["fga"] - league["fg3a"]
    lg_fg2 = (league["fgm"] - league["fg3m"]) / fg2a_total if fg2a_total > 0 else 0.0
    ts_denominator = 2.0 * (league["fga"] + 0.44 * league["fta"])
    lg_ts = league["pts"] / ts_denominator if ts_denominator > 0 else 1.0

    out: dict[str, dict[str, float]] = {}
    for entry in entries:
        totals, minutes = entry["totals"], float(entry["minutes_total"])
        games = int(entry["games_played"])
        metrics = _raw_box_score_metrics(_accum_from_raw(entry))
        fg2m, fg2a = totals["fgm"] - totals["fg3m"], totals["fga"] - totals["fg3a"]
        metrics["three_pct"] = _shrunk_pct(
            totals["fg3m"], totals["fg3a"], lg_fg3 - THREE_PT_PRIOR_DEFICIT
        )
        metrics["three_rate"] = _per36(totals["fg3a"], minutes)
        metrics["two_pct"] = _shrunk_pct(fg2m, fg2a, lg_fg2)
        metrics["usage36"] = _per36(
            totals["fga"] + 0.44 * totals["fta"] + totals["turnover"], minutes
        )
        metrics["stocks36"] = _per36(totals["stl"] + totals["blk"], minutes)
        metrics["gmsc36"] = _per36(sum(entry.get("game_scores") or []), minutes)
        own_ts_denominator = 2.0 * (totals["fga"] + 0.44 * totals["fta"])
        own_ts = totals["pts"] / own_ts_denominator if own_ts_denominator > 0 else 0.0
        metrics["ts_scoring"] = _per36(totals["pts"], minutes) * own_ts / lg_ts
        metrics["mpg"] = minutes / games if games > 0 else 0.0
        metrics["height"] = float(entry["height_in"])
        out[str(entry["external_ref"])] = metrics
    return out


def _raw_advanced(entry: Mapping) -> dict[str, float] | None:
    """The three advanced metrics from a raw file's advanced sums, oriented higher is
    better, or None when the player has no advanced block."""
    block = entry.get("advanced")
    if not block:
        return None
    sums = block["sums"]
    minutes = float(entry["minutes_total"])
    matchup_fga = sums.get("matchup_fga", 0.0)
    matchup_pct = sums.get("matchup_fgm", 0.0) / matchup_fga if matchup_fga > 0 else 0.5
    return {
        "on_ball_defense": -matchup_pct,
        "screen_setting": _per36(sums.get("screen_assists", 0.0), minutes),
        "motor": _per36(
            sums.get("loose_balls_recovered_total", 0.0) + sums.get("charges_drawn", 0.0), minutes
        ),
    }


def season_evidence(season: int, raw: Mapping, legacy: LegacyIndex) -> SeasonEvidence:
    entries = sorted(raw["players"], key=lambda e: str(e["external_ref"]))
    metrics = raw_metrics(entries)
    populations = {
        name: sorted(m[name] for m in metrics.values())
        for name in (*BLENDED_METRICS, *PHYSICAL_METRICS, "mpg")
        if name not in ADVANCED_METRICS
    }

    advanced_present = bool(raw.get("advanced_present")) and season >= _ADVANCED_MIN_SEASON
    raw_adv: dict[str, dict[str, float]] = {}
    if advanced_present:
        for entry in entries:
            adv = _raw_advanced(entry)
            if adv is not None:
                raw_adv[str(entry["external_ref"])] = adv
    adv_populations = (
        {name: sorted(a[name] for a in raw_adv.values()) for name in ADVANCED_METRICS}
        if raw_adv
        else {}
    )

    players: dict[str, PlayerEvidence] = {}
    for entry in entries:
        pid = str(entry["external_ref"])
        z = {
            name: _percentile_z(metrics[pid][name], populations[name])
            for name in populations
            if name != "mpg"
        }
        source: str | None = None
        if pid in raw_adv:
            for name in ADVANCED_METRICS:
                z[name] = _percentile_z(raw_adv[pid][name], adv_populations[name])
            source = "raw"
        elif season >= _ADVANCED_MIN_SEASON:
            recovered = legacy.advanced_z(season, pid)
            if recovered is not None:
                z.update(recovered)
                source = "recovered"
        players[pid] = PlayerEvidence(
            raw=entry,
            minutes=float(entry["minutes_total"]),
            games=int(entry["games_played"]),
            z=z,
            mpg_z=_percentile_z(metrics[pid]["mpg"], populations["mpg"]),
            advanced_source=source,
        )
    return SeasonEvidence(season=season, advanced_present=advanced_present, players=players)


# --------------------------------------------------------------------------- position


@dataclass(frozen=True)
class PositionFacts:
    """What the position refinement reads for one player-season."""

    bdl_position: str
    height_in: float
    ast_share: float  # ast / (fga + 0.44 fta + tov): assists relative to the ball a player uses
    reb36: float
    qualified: bool  # thresholds and scalers come from the qualified pool only


def _mean_sd(values: Sequence[float]) -> tuple[float, float]:
    centre = sum(values) / len(values)
    spread = (sum((v - centre) ** 2 for v in values) / len(values)) ** 0.5
    return centre, spread if spread > 1e-9 else 1.0


def resolve_positions(facts: Mapping[str, PositionFacts]) -> dict[str, Position]:
    """A 5-slot position per player from BDL's coarse label plus what the box score shows.

    The ETL maps 'G'->PG and 'F'->SF blindly, which built 2023 as 242 PG / 207 SF / 52 C /
    38 SG / 33 PF (critic M3). Position now matters: `POSITION_RATING_OFFSETS` are added
    to all 30 real fields and the residual regression conditions on it. The refinement is
    deterministic and pool-relative (each split is at the MEDIAN score of its BDL group
    among the qualified players, so a season's mix does not depend on absolute levels):

    * 'G': PG if `ast_share` is at or above the median of the 'G' group, else SG.
    * 'F': PF if `0.5 z(height) + 0.5 z(reb36)` is at or above the median of the 'F'
      group, else SF.
    * 'G-F' / 'F-G': SF if `0.5 z(height) - 0.5 z(ast_share)` is at or above the median
      of the two wing groups pooled, else SG; the label's order shifts that score by
      -0.25 for 'G-F' and +0.25 for 'F-G' (z units), so it breaks near-ties.
    * 'F-C' / 'C-F' -> PF and 'C' -> C, as the ETL does; an unknown label -> SF.

    z-scores use the qualified pool's mean and SD. A group with no qualified player (or a
    pool of none) falls back to the ETL's blind mapping."""
    qualified = [f for f in facts.values() if f.qualified]
    if not qualified:
        return {ref: _resolve_position(f.bdl_position) for ref, f in facts.items()}
    h_mean, h_sd = _mean_sd([f.height_in for f in qualified])
    r_mean, r_sd = _mean_sd([f.reb36 for f in qualified])
    a_mean, a_sd = _mean_sd([f.ast_share for f in qualified])

    def forward(f: PositionFacts) -> float:
        return 0.5 * (f.height_in - h_mean) / h_sd + 0.5 * (f.reb36 - r_mean) / r_sd

    def wing(f: PositionFacts) -> float:
        base = 0.5 * (f.height_in - h_mean) / h_sd - 0.5 * (f.ast_share - a_mean) / a_sd
        return base + {"G-F": -0.25, "F-G": 0.25}.get(f.bdl_position, 0.0)

    def group_median(labels: tuple[str, ...], score) -> float | None:
        values = sorted(score(f) for f in qualified if f.bdl_position in labels)
        if not values:
            return None
        mid = len(values) // 2
        return values[mid] if len(values) % 2 else (values[mid - 1] + values[mid]) / 2.0

    guard_cut = group_median(("G",), lambda f: f.ast_share)
    forward_cut = group_median(("F",), forward)
    wing_cut = group_median(("G-F", "F-G"), wing)
    out: dict[str, Position] = {}
    for ref, f in facts.items():
        label = f.bdl_position
        if label == "G" and guard_cut is not None:
            out[ref] = Position.PG if f.ast_share >= guard_cut else Position.SG
        elif label == "F" and forward_cut is not None:
            out[ref] = Position.PF if forward(f) >= forward_cut else Position.SF
        elif label in ("G-F", "F-G") and wing_cut is not None:
            out[ref] = Position.SF if wing(f) >= wing_cut else Position.SG
        else:
            out[ref] = _resolve_position(label)
    return out


def _position_facts(entry: Mapping, qualified: bool) -> PositionFacts:
    totals, minutes = entry["totals"], float(entry["minutes_total"])
    used = totals["fga"] + 0.44 * totals["fta"] + totals["turnover"]
    return PositionFacts(
        bdl_position=entry.get("bdl_position") or "",
        height_in=float(entry["height_in"]),
        ast_share=totals["ast"] / used if used > 0 else 0.0,
        reb36=_per36(totals["oreb"] + totals["dreb"], minutes),
        qualified=qualified,
    )


# --------------------------------------------------------------------------- regression


def _solve_linear(matrix: list[list[float]], rhs: list[float]) -> list[float]:
    """Gauss-Jordan with partial pivoting for the small (<= 6x6) normal equations."""
    n = len(rhs)
    aug = [row[:] + [rhs[i]] for i, row in enumerate(matrix)]
    for col in range(n):
        pivot = max(range(col, n), key=lambda r: abs(aug[r][col]))
        aug[col], aug[pivot] = aug[pivot], aug[col]
        diag = aug[col][col]
        if abs(diag) < 1e-12:
            continue
        for row in range(n):
            if row != col:
                factor = aug[row][col] / diag
                if factor:
                    aug[row] = [a - factor * b for a, b in zip(aug[row], aug[col], strict=True)]
    return [aug[i][n] / aug[i][i] if abs(aug[i][i]) >= 1e-12 else 0.0 for i in range(n)]


def fit_ols(design: Sequence[Sequence[float]], y: Sequence[float]) -> list[float]:
    """Least-squares coefficients for `design` (rows of regressors incl. intercept),
    with a hair of ridge so a collinear or empty column cannot break the solve."""
    k = len(design[0])
    xtx = [[0.0] * k for _ in range(k)]
    xty = [0.0] * k
    for row, target in zip(design, y, strict=True):
        for i in range(k):
            xty[i] += row[i] * target
            for j in range(k):
                xtx[i][j] += row[i] * row[j]
    for i in range(k):
        xtx[i][i] += 1e-9
    return _solve_linear(xtx, xty)


def residual_u(
    values: Mapping[str, float],
    impact: Mapping[str, float],
    position: Mapping[str, Position],
    fit_ids: Sequence[str],
) -> dict[str, float]:
    """Standardised residual `u` of `values` after removing dependence on `impact` and
    position, regressed over `fit_ids` (the qualified pool) and applied to every id in
    `values`. Regressors: intercept, impact, a dummy per position present in the fit
    sample except the first (the baseline). Residual SD is taken over the fit sample."""
    fit = [pid for pid in fit_ids if pid in values]
    if len(fit) < 3:
        return dict.fromkeys(values, 0.0)
    present = [p for p in POSITIONS if any(position[pid] == p for pid in fit)]
    dummies = present[1:]

    def row(pid: str) -> list[float]:
        return [1.0, impact[pid], *(1.0 if position[pid] == p else 0.0 for p in dummies)]

    coefs = fit_ols([row(pid) for pid in fit], [values[pid] for pid in fit])

    def resid(pid: str) -> float:
        return values[pid] - sum(c * x for c, x in zip(coefs, row(pid), strict=True))

    fit_resid = [resid(pid) for pid in fit]
    mean = sum(fit_resid) / len(fit_resid)
    sd = (sum((r - mean) ** 2 for r in fit_resid) / len(fit_resid)) ** 0.5
    if sd < _MIN_RESIDUAL_SD:
        return dict.fromkeys(values, 0.0)
    return {pid: resid(pid) / sd for pid in values}


# --------------------------------------------------------------------------- evidence swap


def _standardise(values: Mapping[str, float]) -> dict[str, float]:
    centre, spread = _mean_sd(list(values.values()))
    return {ref: (v - centre) / spread for ref, v in values.items()}


def evidence_rank_swap(
    values: Mapping[str, int], evidence: Mapping[str, float], *, weight: float = 1.0
) -> dict[str, int]:
    """RPC-4: the multiset of `values` re-assigned so the ref with the highest key holds
    the highest value, the next the next, and so on. The key is
    `weight * z(evidence) + (1 - weight) * z(value)`, both standardised over the cell;
    ties break by `external_ref` ascending, so the result is deterministic. At
    `weight = 0` every value stays where it was (equal values may trade places, which
    changes nothing)."""
    if len(values) < 2:
        return dict(values)
    ev = _standardise({ref: evidence[ref] for ref in values})
    lv = _standardise({ref: float(v) for ref, v in values.items()})
    key = {ref: weight * ev[ref] + (1.0 - weight) * lv[ref] for ref in values}
    order = sorted(values, key=lambda ref: (-key[ref], ref))
    ranked_values = sorted(values.values(), reverse=True)
    return dict(zip(order, ranked_values, strict=True))


def swap_cells(
    real: Mapping[str, dict[str, int]],
    evidence: Mapping[str, Mapping[str, float]],
    position: Mapping[str, Position],
    qualified: Sequence[str],
    *,
    weight: float,
    fields: Sequence[str] = SWAP_FIELDS,
) -> dict[str, dict[str, int]]:
    """`real` with each `fields` entry permuted within every position's qualified
    players (RPC-4-2: unqualified rows are left as the level formula made them, so a
    300-minute player can never inherit a star's value and the qualified pool's
    distribution is exactly invariant). Returns new per-player dicts."""
    out = {ref: dict(ratings) for ref, ratings in real.items()}
    for name in fields:
        for pos in POSITIONS:
            cell = {
                ref: out[ref][name]
                for ref in qualified
                if position[ref] == pos and name in out[ref] and ref in evidence[name]
            }
            for ref, value in evidence_rank_swap(cell, evidence[name], weight=weight).items():
                out[ref][name] = value
    return out


def position_residual(
    values: Mapping[str, float], position: Mapping[str, Position], fit_ids: Sequence[str]
) -> dict[str, float]:
    """`values` minus its position's mean over `fit_ids`, divided by the SD of that
    residual over `fit_ids` (RPC-10's `u_reach`: residualised on position only)."""
    fit = [ref for ref in fit_ids if ref in values]
    if len(fit) < 3:
        return dict.fromkeys(values, 0.0)
    by_pos: dict[Position, list[float]] = defaultdict(list)
    for ref in fit:
        by_pos[position[ref]].append(values[ref])
    centre = {pos: sum(v) / len(v) for pos, v in by_pos.items()}
    overall = sum(values[ref] for ref in fit) / len(fit)

    def resid(ref: str) -> float:
        return values[ref] - centre.get(position[ref], overall)

    _, spread = _mean_sd([resid(ref) for ref in fit])
    return {ref: resid(ref) / spread for ref in values}


def wingspan_estimate(height_in: float, u_reach: float) -> int:
    """RPC-10-1: `round(height + 3.5 + 1.8 * u_reach)` within `[height - 1, height + 9]`."""
    lo, hi = WINGSPAN_CLAMP
    value = round(height_in + WINGSPAN_OFFSET_MEAN + WINGSPAN_INCHES_PER_SD * u_reach)
    return int(_clamp(value, height_in + lo, height_in + hi))


