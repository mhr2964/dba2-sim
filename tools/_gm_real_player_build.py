class LegacyIndex:
    """Read-only view of the existing seed files for the two things raw files do not
    carry: the team object (id, city, name) and, without an advanced endpoint, the
    three advanced ratings. Lazy per season; a missing season file is an empty season."""

    def __init__(self, legacy_dir: Path) -> None:
        self._dir = legacy_dir
        self._cache: dict[int, dict[str, Mapping]] = {}
        self._teams: dict[int, dict[str, Mapping]] = {}

    def _rows(self, season: int) -> dict[str, Mapping]:
        if season not in self._cache:
            path = self._dir / f"{season}.json"
            rows: dict[str, Mapping] = {}
            teams: dict[str, Mapping] = {}
            if path.exists():
                for row in json.loads(path.read_text(encoding="utf-8"))["players"]:
                    rows[str(row["external_ref"])] = row
                    team = row.get("team")
                    if team and team.get("abbreviation"):
                        teams.setdefault(team["abbreviation"], team)
            self._cache[season] = rows
            self._teams[season] = teams
        return self._cache[season]

    def advanced_z(self, season: int, external_ref: str) -> dict[str, float] | None:
        """The player-season's three advanced z values, or None. A legacy (version 1)
        row is inverted from its rating; a version-2 row carries them in its meta.
        Version-2 RATINGS are never inverted: their scale is `T + offset + 8u`."""
        row = self._rows(season).get(external_ref)
        if row is None:
            return None
        meta = row.get("meta") or {}
        if meta.get("builder_version") == REAL_BUILDER_VERSION:
            stored = meta.get("advanced_z")
            return {k: float(v) for k, v in stored.items()} if stored else None
        if meta.get("band") != "advanced_tracking":
            return None
        weight = _clamp(float(meta.get("minutes_total", 0.0)) / FULL_CONFIDENCE_MINUTES, 0.0, 1.0)
        if weight < RECOVERY_MIN_WEIGHT:
            # `(rating - 70) / (12 * w)` divides the int rating's +-0.5 rounding by a tiny w:
            # below this the recovered z is mostly noise, so read it as league average.
            return dict.fromkeys(ADVANCED_REAL_FIELDS, 0.0)
        ratings = row["ratings"]
        limit = RECOVERED_Z_LIMIT
        return {
            name: _clamp((ratings[name] - 70.0) / (12.0 * weight), -limit, limit)
            for name in ADVANCED_REAL_FIELDS
        }

    def team(self, season: int, abbreviation: str) -> Mapping:
        """The team object for an abbreviation, from the same season if present, else
        the nearest season that has it, else a bare placeholder."""
        self._rows(season)
        if abbreviation in self._teams[season]:
            return self._teams[season][abbreviation]
        for other in sorted(range(season - 6, season + 7), key=lambda s: abs(s - season)):
            self._rows(other)
            if abbreviation in self._teams[other]:
                return self._teams[other][abbreviation]
        return {
            "id": None,
            "abbreviation": abbreviation,
            "city": abbreviation,
            "name": abbreviation,
            "full_name": abbreviation,
        }


