"""Offline builder: raw BDL season evidence -> version-2 real-player seeds
(RPD-8-2..9 in docs/design/real-player-ratings-v2.md).

No network, no key, no clock: the output is a deterministic function of the raw files
(and, for two things the raw files do not carry, of the legacy seeds -- see below). A
player's output depends on the WHOLE season pool by design (the quantile map and the
residual regression are per-season), and on the priors that are on disk (a season's
blend reads up to three earlier raw files), so the FINAL seed set must be built with
every raw season present; a partial build prints which priors it lacked.

**Pipeline per season** (each step names the design decision it implements):

1. Evidence (RPD-8-5). Per player-season, box-score metrics -> percentile z within the
   season's whole player pool (`_gm_real_player_etl._percentile_z`, so the 12 existing
   metrics are the ETL's own numbers). The three advanced metrics come from raw
   advanced sums when the raw file has them, else are RECOVERED from the legacy seed
   row as `(rating - 70) / (12 * w)`, `w = min(minutes / 1500, 1)`, clamped to the range
   `_percentile_z` can emit (+-3.09) and taken as 0 when `w < 0.15` (the int rating's
   rounding would otherwise be amplified into noise): the advanced endpoint is
   unavailable to this workspace (design doc, "Advanced endpoint unavailable").
2. Blend (RPD-8-4, option B'). Thin seasons are filled toward 1500 minutes from up to
   three earlier seasons: `avail = prior_minutes * 0.7**back`, take up to the gap, unfilled
   part shrinks toward 0. Identical to the ETL for anyone with 1500+ minutes.
3. Impact `I` (RPD-8-2) = `0.45 z(GmSc/36) + 0.25 z(pts/36 * TS% / lg TS%) + 0.30 z(mpg)`;
   the two performance terms are blended, the minutes-per-game term is not.
4. Quantile map (RPD-8-3). The QUALIFIED pool (blended effective minutes >= 300) is
   ranked by `I` and rank -> talent `T` through the synthetic tier ladder
   (30 x N(84,4), 120 x N(76,3), 90 x N(70,3), 180 x N(63,3) quantile points, pooled
   and sorted so the map is MONOTONE in rank) then a linear tail to the 40 floor.
   Unqualified players are placed by the same map and capped at the bench ceiling 66.
5. Real fields (RPD-8-6). `z_field = sum(weight * z_eff[metric])`, residualised on `I`
   and position over the qualified pool, standardised to `u`; the rating is
   `clamp(T + POSITION_RATING_OFFSETS[pos][f] + 8u)`. The other fields are synthetic,
   generated by `tools/_real_synth.py` at the talent `T'` that makes the displayed
   overall equal `round(T)`; the two hidden fields (`potential`, `potential_variance`)
   are generated at `T`, so the correction `T' - T` never reaches them.
5b. Evidence-rank swap (RPC-4, docs/design/real-player-rating-calibration.md), applied
   to `SWAP_FIELDS` between the level formula and the synthetic fit: within each
   position's QUALIFIED players the cell's existing multiset of ratings is re-assigned
   in order of `w * z(evidence) + (1 - w) * z(level value)`, where the evidence is the
   field's blended z before `residual_u` and `w = Tuning.swap_evidence_weight` (0.70,
   see there; ties by `external_ref`), so shot blocking, not talent, decides who holds
   the high `rim_protection` values his position produces. No value is new, so every
   per-position distribution is unchanged; unqualified rows keep the level formula's
   value. The fit then runs on the swapped value, so `T'` and the synthetic remainder
   follow it.
5c. Wingspan (RPC-10). BDL has none, so the row stores an estimate the league
   loaders read instead of drawing one per league and roster slot:
   `round(height + 3.5 + 1.8 * u_reach)`, clamped to `[height - 1, height + 9]` (the
   synthetic generator's own mean offset and clamp), where `u_reach` is a blocks-and-
   rebounds evidence blend, position-centred and standardised over the qualified pool.
   It decides who is long; the population's centre stays at height + 3.5.
6. Team (RPD-8-9), from the raw season-opening abbreviation; the full team object
   (id, city, name) comes from the legacy seeds. Peak ages (RPD-8-9) are recomputed
   AFTER every requested season is built, from version-2 seasons only: the requested ones
   plus any already in the out-dir, so a partial rebuild agrees with `--all`.

Interpretation calls the design doc left open, kept visible here: the tier ladder is
sorted so rank -> talent is monotone (a per-tier assignment would rate rank 31 eight
points above rank 30); the tail starts at the ladder's last value (about 54.7, not the
doc's 60, which would sit ABOVE rank 420); extra `meta` keys (`talent`,
`synthetic_talent`, `impact`, `effective_minutes`, `qualified`, `advanced_z`,
`advanced_source`, `prior_seasons`: the raw seasons that fed the blend) let the
acceptance report run from any out-dir and let a rebuilt seed serve as its own
advanced-z source next time.

Refuses to write into `seeds/real_players` unless `--allow-seeds-dir` is given AND
`--all` is used (a partial build there would leave the committed seasons inconsistent);
the default out-dir is a scratch directory outside the repo's seeds.

Usage:
    python -m tools._gm_real_player_build --all [--out-dir DIR]
    python -m tools._gm_real_player_build 2015 2016 2017 [--out-dir DIR]
"""

